SUBJECT_COUNT = 3
NAME_INDEX = 0

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def sum_scores(student):
    """Return the total of a student's numeric scores, skipping the name at index 0."""
    total = 0
    for index in range(NAME_INDEX + 1, len(student)):
        total = total + student[index]
    return total


def average_score(student):
    return sum_scores(student) / SUBJECT_COUNT


def count_above_class_average(students):
    """Return how many students scored above the class average."""
    class_average_total = 0
    for student in students:
        class_average_total = class_average_total + average_score(student)
    class_avg = class_average_total / len(students)

    count = 0
    for student in students:
        if average_score(student) > class_avg:
            count = count + 1
    return count


print("REPORT")

for student in students:
    total = sum_scores(student)
    average = average_score(student)

    if average >= 90:
        grade = "A"
    elif average >= 80:
        grade = "B"
    elif average >= 70:
        grade = "C"
    elif average >= 60:
        grade = "D"
    else:
        grade = "F"

    print(f"{student[NAME_INDEX]}{total}{average}{grade}")

class_average_total = 0

for student in students:
    average = average_score(student)
    class_average_total = class_average_total + average

print(f"Class average:{class_average_total / len(students)}")
print(f"Students above class average:{count_above_class_average(students)}")

highest_average = 0
topper_name = ""

for student in students:
    average = average_score(student)

    if average > highest_average:
        highest_average = average
        topper_name = student[NAME_INDEX]

print(f"Topper:{topper_name}{highest_average}")

